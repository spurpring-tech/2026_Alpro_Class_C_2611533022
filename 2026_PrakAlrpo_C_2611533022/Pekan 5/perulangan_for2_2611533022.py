# Perulangan ini menggunakan fungsi input()

ulang_3022 = int(input("Masukkan jumlah oerulangan: "))
print("Perulangan ke-0 sampai ke-",ulang_3022-1)
for i_3022 in range(ulang_3022):
    print(i_3022, end=" ")
print()
print("perulangan ke-1 sampai ke-",ulang_3022)
for i_3022 in range(1, ulang_3022+1):
    print(i_3022, end=" ")